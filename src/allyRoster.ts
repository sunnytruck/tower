import type { Stats, Ability } from "./data.ts";

/** HP, damage, attack interval, range, speed, cost, cooldown, HP knockback segments. */
type Combat = readonly [
  number,
  number,
  number,
  number,
  number,
  number,
  number,
  number?,
];
function ally<const Id extends string>(
  id: Id,
  rarity: number,
  material: string,
  name: string,
  role: string,
  combat: Combat,
  color: string,
  options: {
    area?: boolean;
    size?: number;
    splash?: number;
    ability?: Ability;
    symbol?: string;
  } = {},
) {
  const [hp, damage, interval, range, speed, cost, cooldown, knockback = 1] =
    combat;
  const stats: Stats = {
    name,
    role,
    hp,
    damage,
    interval,
    range,
    speed,
    cost,
    cooldown,
    knockback,
    color,
    area: options.area ?? false,
    size: options.size ?? 1,
    symbol: options.symbol ?? name.slice(0, 1),
    ...(options.splash !== undefined ? { splash: options.splash } : {}),
    ...(options.ability ? { ability: options.ability } : {}),
  };
  return { id, rarity, material, stats };
}
